// App icons from one vector design (108×108 adaptive-icon grid, content inside the 66-unit safe
// circle). Writes Android adaptive icons (vector, Android 8+) for each app and SVG previews.
//   node tools/icons/make-icons.mjs
// Mark: a white car seen from the front (instantly "car service"), plus a badge per app:
// staff = wrench (workshop), customer = check (approve / done), gateway = message dots.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const W = "#FFFFFF";
const car = (bg) => [
  // cabin with windshield
  { d: "M40,46 L44.5,36.5 Q45.5,34 48,34 L60,34 Q62.5,34 63.5,36.5 L68,46 Z", fill: W },
  { d: "M43.6,44.6 L46.6,38.2 L61.4,38.2 L64.4,44.6 Z", fill: bg },
  // body
  { d: "M37,44.5 H71 Q76,44.5 76,49.5 V57.5 Q76,62 71.5,62 H36.5 Q32,62 32,57.5 V49.5 Q32,44.5 37,44.5 Z", fill: W },
  // headlights and grille (cut-outs in the background colour)
  { d: "M36,52.5 a3.2,3.2 0 1,0 6.4,0 a3.2,3.2 0 1,0 -6.4,0 Z", fill: bg },
  { d: "M65.6,52.5 a3.2,3.2 0 1,0 6.4,0 a3.2,3.2 0 1,0 -6.4,0 Z", fill: bg },
  { d: "M47.5,51.2 H60.5 Q62,51.2 62,52.7 V55.3 Q62,56.8 60.5,56.8 H47.5 Q46,56.8 46,55.3 V52.7 Q46,51.2 47.5,51.2 Z", fill: bg },
  // wheels
  { d: "M35,61 H42.5 V66.5 Q42.5,68.5 40.5,68.5 H37 Q35,68.5 35,66.5 Z", fill: W },
  { d: "M65.5,61 H73 V66.5 Q73,68.5 71,68.5 H67.5 Q65.5,68.5 65.5,66.5 Z", fill: W },
];
const badge = (color, inner) => [
  { d: "M61.5,70 a9.5,9.5 0 1,0 19,0 a9.5,9.5 0 1,0 -19,0 Z", fill: color, stroke: W, strokeWidth: 1.6 },
  ...inner,
];
const wrench = [
  { d: "M67.1,76.1 L64.9,73.9 L73.9,64.9 L76.1,67.1 Z", fill: W },
  { d: "M72.3,65.5 a3.3,3.3 0 1,0 6.6,0 a3.3,3.3 0 1,0 -6.6,0 Z", fill: W },
  { d: "M75.6,63.8 a1.7,1.7 0 1,0 3.4,0 a1.7,1.7 0 1,0 -3.4,0 Z", fill: "#F59E0B" },
  { d: "M64.4,75.4 a1.7,1.7 0 1,0 3.4,0 a1.7,1.7 0 1,0 -3.4,0 Z", fill: W },
];
const check = [{ d: "M66.2,70.4 L69.6,73.8 L76,66.8", stroke: W, strokeWidth: 2.6, cap: "round" }];
const dots = [
  { d: "M65.6,70 a1.6,1.6 0 1,0 3.2,0 a1.6,1.6 0 1,0 -3.2,0 Z", fill: W },
  { d: "M69.4,70 a1.6,1.6 0 1,0 3.2,0 a1.6,1.6 0 1,0 -3.2,0 Z", fill: W },
  { d: "M73.2,70 a1.6,1.6 0 1,0 3.2,0 a1.6,1.6 0 1,0 -3.2,0 Z", fill: W },
];

const apps = {
  staff: { bg: "#0E7490", shapes: (bg) => [...car(bg), ...badge("#F59E0B", wrench)] },
  customer: { bg: "#1D4ED8", shapes: (bg) => [...car(bg), ...badge("#16A34A", check)] },
  sms_gateway: { bg: "#475569", shapes: (bg) => [...car(bg), ...badge("#7C3AED", dots)] },
};

const svgPath = (s) =>
  `<path d="${s.d}" fill="${s.fill ?? "none"}"${s.stroke ? ` stroke="${s.stroke}" stroke-width="${s.strokeWidth}" stroke-linecap="${s.cap ?? "butt"}" stroke-linejoin="round"` : ""}/>`;
const vectorPath = (s) =>
  `    <path android:pathData="${s.d}" android:fillColor="${s.fill ?? "#00000000"}"` +
  (s.stroke ? ` android:strokeColor="${s.stroke}" android:strokeWidth="${s.strokeWidth}" android:strokeLineCap="${s.cap ?? "butt"}" android:strokeLineJoin="round"` : "") + "/>";

const root = new URL("../../", import.meta.url);
const preview = new URL("tools/icons/preview/", root);
mkdirSync(preview, { recursive: true });

for (const [app, { bg, shapes }] of Object.entries(apps)) {
  const list = shapes(bg);
  // Square preview with a rounded mask, like a launcher shows it.
  writeFileSync(new URL(`${app}.svg`, preview),
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72" width="512" height="512">` +
    `<rect x="18" y="18" width="72" height="72" rx="16" fill="${bg}"/>${list.map(svgPath).join("")}</svg>`);
  // Android adaptive icon: vector foreground + colour background.
  const res = new URL(`apps/${app}/android/app/src/main/res/`, root);
  mkdirSync(new URL("drawable/", res), { recursive: true });
  mkdirSync(new URL("mipmap-anydpi-v26/", res), { recursive: true });
  mkdirSync(new URL("values/", res), { recursive: true });
  writeFileSync(new URL("drawable/ic_launcher_foreground.xml", res),
    `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/icons/make-icons.mjs -->\n` +
    `<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="108dp" android:height="108dp"\n` +
    `    android:viewportWidth="108" android:viewportHeight="108">\n${list.map(vectorPath).join("\n")}\n</vector>\n`);
  writeFileSync(new URL("values/ic_launcher_background.xml", res),
    `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">${bg}</color>\n</resources>\n`);
  writeFileSync(new URL("mipmap-anydpi-v26/ic_launcher.xml", res),
    `<?xml version="1.0" encoding="utf-8"?>\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n` +
    `    <background android:drawable="@color/ic_launcher_background"/>\n    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n` +
    `    <monochrome android:drawable="@drawable/ic_launcher_foreground"/>\n</adaptive-icon>\n`);
  console.log(`• ${app}: adaptive icon + preview`);
}
writeFileSync(new URL("index.html", preview),
  `<!doctype html><meta charset="utf-8"><title>Icons</title><body style="margin:0;padding:24px;background:#e5e7eb;display:flex;gap:28px;align-items:end;font:14px system-ui">` +
  Object.keys(apps).map((a) => `<figure style="margin:0;text-align:center"><img src="${a}.svg" width="160" height="160"><figcaption>${a}</figcaption>` +
    `<img src="${a}.svg" width="48" height="48" style="display:block;margin:8px auto 0"></figure>`).join("") + `</body>`);

// Web dashboard icons (favicon, PWA icons) and legacy Android PNGs, rendered from the same SVGs.
const { Resvg } = await import("@resvg/resvg-js");
const png = (svg, size) => new Resvg(svg, { fitTo: { mode: "width", value: size } }).render().asPng();
const staffSvg = readFileSync(new URL("staff.svg", preview), "utf8");
const web = new URL("apps/web/web/", root);
writeFileSync(new URL("favicon.png", web), png(staffSvg, 64));
for (const s of [192, 512]) {
  writeFileSync(new URL(`icons/Icon-${s}.png`, web), png(staffSvg, s));
  writeFileSync(new URL(`icons/Icon-maskable-${s}.png`, web), png(staffSvg.replace('rx="16"', 'rx="0"'), s));
}
// Older launchers that ignore adaptive icons read mipmap PNGs.
const dens = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
for (const app of Object.keys(apps)) {
  const svg = readFileSync(new URL(`${app}.svg`, preview), "utf8");
  for (const [d, s] of Object.entries(dens)) {
    writeFileSync(new URL(`apps/${app}/android/app/src/main/res/mipmap-${d}/ic_launcher.png`, root), png(svg, s));
  }
}
console.log("• web favicon + PWA icons, Android mipmap PNGs");
